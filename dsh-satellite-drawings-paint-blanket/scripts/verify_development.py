def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def code_fingerprint(root=ROOT):
 # Inventory actual versioned (and new nonignored) source, never a hand-maintained
 # list of build directories. In particular plugin/public is regenerated by build.
 names=subprocess.check_output(['git','ls-files','--cached','--others','--exclude-standard','-z'],cwd=root).decode().split('\0')
 roots=('service/','packages/','plugins/','contracts/','scripts/','tests/','fixtures/')
 configs={'package.json','package-lock.json','playwright.b09.config.ts', 'playwright.b12.config.ts', 'playwright.b13.config.ts','playwright.b13-r1.config.ts','playwright.b13-r2.config.ts','playwright.b13-r3.config.ts','playwright.b13-r4.config.ts','tsconfig.b07.json','pyproject.toml','uv.lock'}
 names=sorted({n for n in names if n.startswith(roots) or n in configs})
 return hashlib.sha256(json.dumps([(n,digest(root/n) if (root/n).is_file() else 'missing') for n in names],separators=(',',':')).encode()).hexdigest()

def assess(commands,counts,checks,missing,review_ok):
 if any(c['exit_code'] for c in commands) or counts['failed'] or any(c['status']=='fail' for c in checks):return 'failed'
 if counts['required']<=0 or counts['passed']!=counts['required'] or counts['skipped_required'] or missing or any(c['status']!='pass' for c in checks):return 'blocked'
 return 'passed' if review_ok else 'blocked'

def review_check(root,revision,fingerprint):
 """An independent reviewer supplies this record; implementation never manufactures it."""
 try:
  review=json.loads((root/'docs/evidence/B09/independent-review.json').read_text())
  assert review['decision']=='approved' and review['scope']=='B09-development' and review['reviewer']
  assert review['code_fingerprint']==fingerprint
  if review['code_revision']!=revision:
   assert subprocess.run(['git','merge-base','--is-ancestor',review['code_revision'],revision],cwd=root,capture_output=True).returncode==0
  assert review['evidence_refs']
  for item in review['evidence_refs']:
   p=(root/item['path']).resolve();assert p.is_relative_to(root.resolve()) and digest(p)==item['sha256']
  return True
 except (OSError,ValueError,KeyError,AssertionError,TypeError):return False

