import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1200}});
page.setDefaultTimeout(30000);
process.on('unhandledRejection',async(error)=>{console.log(String(error));await page.screenshot({path:'work/simple-v1-evidence/probe-failure.png',fullPage:true});await browser.close();process.exit(1);});
page.on('pageerror',error=>console.log('PAGEERROR',String(error)));
page.on('response',response=>{if(response.status()>=400)console.log('HTTP',response.status(),new URL(response.url()).pathname);});
fs.mkdirSync('work/simple-v1-evidence',{recursive:true});
await page.goto('http://127.0.0.1:18890/');
console.log('host loaded');
await page.getByRole('button',{name:'多层图纸',exact:true}).click();
console.log('entry opened');
const frame=page.frameLocator('iframe');
console.log('iframe content',await frame.locator('body').innerText());
await frame.getByTestId('identity').waitFor({state:'attached'});
await frame.getByRole('button',{name:'新建工程',exact:true}).click();
await expect(frame.getByLabel('导入 STEP',{exact:true})).toBeEnabled();
await frame.getByTestId('project').filter({hasText:/[a-f0-9]{32}/}).waitFor({state:'attached'});
console.log('project created');
const imported=page.waitForResponse(response=>new URL(response.url()).pathname.endsWith('/imports')&&response.request().method()==='POST');
await frame.getByLabel('导入 STEP',{exact:true}).setInputFiles('fixtures/synthetic/simple-v1/cube-cylinder.step');
const importResponse=await imported;console.log('import submission',importResponse.status(),await importResponse.text());
if(importResponse.status()!==202){console.log('body',await frame.locator('body').innerText());await page.screenshot({path:'work/simple-v1-evidence/probe-failure.png',fullPage:true});await browser.close();process.exit(1);}
await frame.getByTestId('viewer').waitFor({state:'visible',timeout:60000});
await frame.locator('[data-testid=viewer][data-ready=true]').waitFor({timeout:60000});
fs.mkdirSync('work/simple-v1-evidence',{recursive:true});
await page.screenshot({path:'work/simple-v1-evidence/initial-ui.png',fullPage:true});
console.log((await frame.locator('body').innerText()).slice(0,10000));
await browser.close();
